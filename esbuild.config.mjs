import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
const prod = process.argv[2] === 'production';
const context = await esbuild.context({
  banner: { js: '/* Generated by esbuild. Source: src/main.ts */' },
  entryPoints: ['src/main.ts'], bundle: true, platform: 'node',
  external: ['obsidian', 'electron', ...builtinModules, ...builtinModules.map(m => `node:${m}`)],
  format: 'cjs', target: 'es2021', logLevel: 'info',
  sourcemap: prod ? false : 'inline', treeShaking: true,
  outfile: 'main.js', minify: prod,
});
if (prod) { await context.rebuild(); await context.dispose(); }
else { await context.watch(); }
